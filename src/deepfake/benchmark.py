"""End-to-end benchmark: swap only vs swap + frame generation.

Every number printed comes from a timed run on this machine. The input is a
synthetic moving shot of a bundled *fictional* face (assets/bench_face.jpg,
generated by an image model — not a real person), fed through a fake camera
that delivers frames in real time at the requested rate.
"""

from __future__ import annotations

import math
import time
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import Any

import numpy as np

RESOLUTIONS = {"720p": (1280, 720), "1080p": (1920, 1080)}


def bench_face_path() -> Path:
    return Path(str(resources.files("deepfake") / "assets" / "bench_face.jpg"))


class SyntheticCamera:
    """OpenCV-capture lookalike: a face moving smoothly across a textured backdrop."""

    def __init__(self, face_bgr: np.ndarray, size: tuple[int, int], fps: float, frames: int | None) -> None:
        import cv2

        w, h = size
        self.size, self.fps, self.frames = size, fps, frames
        fh = int(h * 0.75)
        fw = int(face_bgr.shape[1] * fh / face_bgr.shape[0])
        self.face = cv2.resize(face_bgr, (fw, fh), interpolation=cv2.INTER_AREA)
        rng = np.random.default_rng(7)
        noise = (rng.random((h // 8, w // 8, 3)) * 80 + 60).astype(np.uint8)
        self.bg = cv2.resize(noise, (w, h), interpolation=cv2.INTER_CUBIC)
        self.i = 0
        self.t_next = None

    def frame_at(self, i: int) -> np.ndarray:
        w, h = self.size
        fh, fw = self.face.shape[:2]
        t = i / self.fps
        # ~0.8 Hz sway plus a slow bob: realistic head-motion speeds for a webcam.
        cx = int((w - fw) / 2 + (w * 0.18) * math.sin(2 * math.pi * 0.8 * t))
        cy = int((h - fh) / 2 + (h * 0.05) * math.sin(2 * math.pi * 0.35 * t))
        out = np.roll(self.bg, int(40 * t) % w, axis=1).copy()
        x0, y0 = max(0, cx), max(0, cy)
        x1, y1 = min(w, cx + fw), min(h, cy + fh)
        out[y0:y1, x0:x1] = self.face[y0 - cy : y1 - cy, x0 - cx : x1 - cx]
        return out

    # OpenCV VideoCapture protocol ------------------------------------
    def read(self):
        if self.frames is not None and self.i >= self.frames:
            return False, None
        now = time.monotonic()
        if self.t_next is None:
            self.t_next = now
        if self.t_next > now:
            time.sleep(self.t_next - now)
        self.t_next += 1.0 / self.fps
        f = self.frame_at(self.i)
        self.i += 1
        return True, f

    def set(self, *_a) -> bool:
        return True

    def release(self) -> None:
        return None


@dataclass
class BenchConfig:
    resolutions: tuple[str, ...] = ("720p", "1080p")
    camera_fps: float = 30.0
    target_fps: float = 60.0
    seconds: float = 8.0
    factors: tuple[int, ...] = (2, 3)
    variant: str = "4.25"
    swap_precision: str = "bf16"


def _swap_only(face: np.ndarray, size: tuple[int, int], precision: str, frames: int = 90) -> dict[str, Any]:
    import torch

    from .pipeline import FaceSwapPipeline, build_config

    cfg = build_config("balanced", device="cuda", backend="alphaface", watermark=True, swap_precision=precision)
    cam = SyntheticCamera(face, size, fps=1e9, frames=None)
    pipe = FaceSwapPipeline(cfg)
    pipe.set_source(face)
    for i in range(8):
        pipe.swap_frame(cam.frame_at(i))
    torch.cuda.synchronize()
    torch.cuda.reset_peak_memory_stats()
    lat = []
    t_all = time.perf_counter()
    for i in range(frames):
        t0 = time.perf_counter()
        pipe.swap_frame(cam.frame_at(i))
        lat.append((time.perf_counter() - t0) * 1000)
    wall = time.perf_counter() - t_all
    lat.sort()
    peak = torch.cuda.max_memory_allocated() / 2**20
    del pipe
    torch.cuda.empty_cache()
    return {
        "swap_fps": round(frames / wall, 1),
        "swap_ms_p50": round(lat[len(lat) // 2], 2),
        "swap_ms_p95": round(lat[int(len(lat) * 0.95)], 2),
        "peak_vram_mb_torch": round(peak, 1),
    }


def _framegen_only(size: tuple[int, int], factor: int, variant: str) -> dict[str, Any]:
    from .framegen import create_backend

    be = create_backend("rife", variant=variant)
    be.initialize(*size)
    try:
        return be.benchmark(size[0], size[1], factor, iterations=80).as_dict()
    finally:
        be.shutdown()


def _pipeline(face: np.ndarray, size: tuple[int, int], cfg: BenchConfig, factor: int | None) -> dict[str, Any]:
    """Real threaded pipeline on the synthetic camera, output to a null sink."""
    import torch

    from .framegen.settings import FrameGenSettings
    from .outputs.sinks import NullSink
    from .pipeline import build_config
    from .realtime import run_realtime

    pcfg = build_config(
        "balanced",
        device="cuda",
        backend="alphaface",
        watermark=True,
        swap_precision=cfg.swap_precision,
        show_metrics=False,
    )
    from dataclasses import replace

    pcfg.preset = replace(pcfg.preset, width=size[0], height=size[1], fps=int(cfg.camera_fps))
    cam = SyntheticCamera(face, size, cfg.camera_fps, frames=None)
    torch.cuda.reset_peak_memory_stats()
    samples: list[dict[str, Any]] = []
    if factor is None:
        fg = FrameGenSettings(enabled=False)
    else:
        fg = FrameGenSettings(enabled=True, factor=factor, variant=cfg.variant, output_fps=cfg.camera_fps * factor)
    res = run_realtime(
        None,
        None,
        NullSink(),
        pcfg,
        fg,
        source_fps=cfg.camera_fps,
        print_stats=False,
        duration_s=cfg.seconds,
        capture=cam,
        source_bgr=face,
        on_stats=samples.append,
    )
    # steady-state rates: skip the first two 1-second samples (model/cuDNN warm-up)
    steady = samples[2:] or samples
    if steady:
        for k in ("output_fps", "sink_fps", "swap_fps", "input_fps"):
            res[k] = round(sum(s[k] for s in steady) / len(steady), 1)
    res["peak_vram_mb_torch"] = round(torch.cuda.max_memory_allocated() / 2**20, 1)
    return res


def recommend(results: dict[str, Any], target_fps: float) -> dict[str, Any]:
    """Pick the smallest multiplier whose *measured* pipeline reached the target cleanly."""
    out: dict[str, Any] = {}
    for res_name, r in results.items():
        base = r["pipeline_no_framegen"]
        choice = {"mode": "off", "reason": "frame generation did not reach the target without extra latency"}
        for key in sorted(k for k in r if k.startswith("pipeline_framegen_")):
            fg = r[key]
            factor = int(key.rsplit("_", 1)[1].rstrip("x"))
            presented = fg.get("output_fps") or 0  # new frames only; held repeats excluded
            held_ratio = fg.get("held_frames", 0) / max(1, fg.get("keyframes", 0) + fg.get("generated_frames", 0))
            if presented >= 0.9 * target_fps and held_ratio < 0.05:
                choice = {
                    "mode": f"{factor}x",
                    "expected_output_fps": presented,
                    "added_latency_ms": _added_latency(base, fg),
                    "reason": f"measured {presented} new frames/s, {held_ratio:.1%} held slots",
                }
                break
        out[res_name] = choice
    return out


def _added_latency(base: dict[str, Any], fg: dict[str, Any]) -> float | None:
    a, b = base.get("total_latency_ms"), fg.get("total_latency_ms")
    if a is None or b is None:
        return None
    return round(b - a, 1)


def run_benchmark(cfg: BenchConfig, *, progress=print) -> dict[str, Any]:
    import cv2
    import torch

    face = cv2.imread(str(bench_face_path()))
    if face is None:
        raise RuntimeError("bundled benchmark face missing")
    report: dict[str, Any] = {
        "gpu": torch.cuda.get_device_name(0),
        "torch": torch.__version__,
        "camera_fps": cfg.camera_fps,
        "target_fps": cfg.target_fps,
        "swap_precision": cfg.swap_precision,
        "framegen_backend": f"rife {cfg.variant}",
        "results": {},
    }
    for name in cfg.resolutions:
        size = RESOLUTIONS[name]
        r: dict[str, Any] = {}
        progress(f"[{name}] AlphaFace swap only …")
        r["swap_only"] = _swap_only(face, size, cfg.swap_precision)
        for f in cfg.factors:
            progress(f"[{name}] RIFE {cfg.variant} {f}x interpolation only …")
            r[f"framegen_only_{f}x"] = _framegen_only(size, f, cfg.variant)
        progress(f"[{name}] full pipeline, NO frame generation ({cfg.seconds:.0f}s) …")
        r["pipeline_no_framegen"] = _pipeline(face, size, cfg, None)
        for f in cfg.factors:
            progress(f"[{name}] full pipeline, frame generation {f}x ({cfg.seconds:.0f}s) …")
            r[f"pipeline_framegen_{f}x"] = _pipeline(face, size, cfg, f)
        report["results"][name] = r
    report["recommendation"] = recommend(report["results"], cfg.target_fps)
    return report
